def fetch_ru(year: int) -> List[dict]:
    """
    获取俄罗斯节假日
    返回格式: [{"date": "YYYY-MM-DD", "name": "节日名称"}, ...]
    """
    events = []

    # 获取该年的特殊假期数据
    special_holidays = RUSSIAN_SPECIAL_HOLIDAYS.get(year, [])

    for start_date, end_date, holiday_name in special_holidays:
        start = datetime.strptime(start_date, "%Y-%m-%d")
        end = datetime.strptime(end_date, "%Y-%m-%d")

        # 计算天数
        days_count = (end - start).days + 1

        # 创建事件
        if days_count == 1:
            # 单日假期
            label = f"🇷🇺 {holiday_name}"
        else:
            # 多日假期，标记连休
            label = f"🇷🇺 {holiday_name} ({days_count}天)"

        events.append({
            "date": start_date,
            "name": label,
            "start_date": start_date,
            "end_date": end_date,
        })

    return events
