def fetch_ru_holidays(year: int) -> List[Tuple[str, str]]:
    """
    获取指定年份的俄罗斯假期
    
    参数:
        year: 年份，如2026等
    
    返回:
        [(假期名称, 日期字符串), ...]
        例如: [("新年假期", "2026-01-01"), ("新年假期", "2026-01-02"), ...]
    """
    holidays = RUSSIAN_HOLIDAYS.get(year, [])
    
    if not holidays:
        print(f"警告：{year}年的俄罗斯假期数据不可用")
    
    return holidays


