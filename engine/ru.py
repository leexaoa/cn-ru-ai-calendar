def fetch_ru_holidays(year: int) -> List[Tuple[str, str]]:
    """
    获取指定年份的俄罗斯假期
    返回: [(节假日名称, 日期字符串), ...]
    """
    holidays = SPECIAL_HOLIDAYS.get(year, [])
    
    if not holidays:
        # 如果没有特殊数据，生成标准假期
        holidays = []
        for name, month_day in RUSSIAN_HOLIDAYS.items():
            date_str = f"{year}-{month_day}"
            holidays.append((name, date_str))
    
    return holidays
