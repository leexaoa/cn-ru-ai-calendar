def fetch_cn_holidays(year: int) -> List[Tuple[str, str]]:
    """
    获取指定年份的中国假期
    
    参数:
        year: 年份，如2024、2025等
    
    返回:
        [(假期名称, 日期字符串), ...]
        例如: [("春节", "2024-02-10"), ("春节", "2024-02-11"), ...]
    """
    holidays = CN_HOLIDAYS.get(year, [])
    
    if not holidays:
        print(f"警告：{year}年的中国假期数据不可用")
    
    return holidays


